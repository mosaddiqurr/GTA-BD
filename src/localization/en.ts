import type { bn } from "./bn";

type DeepPartial<T> = T extends (...a: never[]) => unknown ? T : T extends readonly (infer U)[] ? readonly DeepPartial<U>[] : T extends object ? { [K in keyof T]?: DeepPartial<T[K]> } : T;

// English lines mirror `bn` key for key and index for index: each English string is paired with its Bangla
// by position, so the Bangla voice can still play. Lines that exist only for the voice (every `...Say`
// function, `dealSay`, `busFareWords`, `voiceSample`, `wayIs`, `distanceIs`) and non-text data
// (`prayerHours`) are left out on purpose, so `bn` supplies them.

const cap = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);
/** A generic noun with a small first letter. Names that start with two capitals (SIM, CNG) stay as they are. */
const lc = (s: string): string => (/^[A-Z][^A-Z]/.test(s) ? s.charAt(0).toLowerCase() + s.slice(1) : s);
const ordinal = (n: number): string => {
  const r = n % 100;
  const suffix = r >= 11 && r <= 13 ? "th" : (["th", "st", "nd", "rd"][n % 10] ?? "th");
  return `${n}${suffix}`;
};

